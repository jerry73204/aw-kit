//! End-to-end pipeline integration tests.
//!
//! Each test exercises the full manifest → platform → resolver → codegen → builder → lockfile
//! chain using a mock DockerEngine (no real Docker needed).

use std::{
    cell::RefCell,
    path::{Path, PathBuf},
};

use aw_kit::{
    builder::{self, BuildResult, DockerEngine},
    codegen,
    error::Result,
    lockfile::LockFile,
    manifest::ManifestConfig,
    platform::{self, DockerRuntime, ResolvedPlatform},
    registry,
    resolver::{self, BuildPlan, BuildStep, LayerType},
};

// ---------------------------------------------------------------------------
// Mock Docker engine
// ---------------------------------------------------------------------------

struct MockEngine {
    pulled: RefCell<Vec<String>>,
    built: RefCell<Vec<String>>,
}

impl MockEngine {
    fn new() -> Self {
        Self {
            pulled: RefCell::new(Vec::new()),
            built: RefCell::new(Vec::new()),
        }
    }
}

impl DockerEngine for MockEngine {
    fn pull(&self, image: &str, _platform: &str) -> Result<String> {
        self.pulled.borrow_mut().push(image.to_string());
        Ok(format!("sha256:pull-{:x}", fxhash(image)))
    }

    fn build(
        &self,
        _dockerfile: &Path,
        _context: &Path,
        tag: &str,
        _platform: &str,
    ) -> Result<String> {
        self.built.borrow_mut().push(tag.to_string());
        Ok(format!("sha256:build-{:x}", fxhash(tag)))
    }

    fn inspect_digest(&self, image: &str) -> Result<String> {
        Ok(format!("sha256:inspect-{:x}", fxhash(image)))
    }
}

fn fxhash(s: &str) -> u64 {
    use std::hash::{DefaultHasher, Hash, Hasher};
    let mut h = DefaultHasher::new();
    s.hash(&mut h);
    h.finish()
}

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

fn fixture(name: &str) -> ManifestConfig {
    let path = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("tests/fixtures")
        .join(name);
    ManifestConfig::from_file(&path).unwrap()
}

fn parse_inline(toml: &str) -> ManifestConfig {
    toml::from_str(toml).unwrap()
}

/// Run the full pipeline: resolve → build (mock) → codegen → lock.
fn run_pipeline(manifest: &ManifestConfig) -> (BuildResult, ResolvedPlatform, BuildPlan, PathBuf) {
    let platform = platform::resolve_platform(&manifest.platform).unwrap();
    let plan = resolver::resolve(manifest, &platform).unwrap();
    let dir = tempfile::tempdir().unwrap();
    let project_root = dir.path().to_path_buf();

    // Create any local source dirs that fetch_sources will check.
    for pkg in &manifest.package {
        std::fs::create_dir_all(project_root.join(&pkg.path)).unwrap();
    }
    for patches in manifest.patch.values() {
        for source in patches.values() {
            if let aw_kit::manifest::PatchSource::Path { path } = source {
                std::fs::create_dir_all(project_root.join(path)).unwrap();
            }
        }
    }

    let engine = MockEngine::new();
    let result = builder::execute_plan(&engine, manifest, &plan, &platform, &project_root).unwrap();

    // Keep the dir alive by leaking it (tests are short-lived).
    std::mem::forget(dir);

    (result, platform, plan, project_root)
}


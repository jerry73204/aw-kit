#[test]
fn minimal_desktop_lockfile() {
    let manifest = fixture("minimal.toml");
    let (result, _, _, root) = run_pipeline(&manifest);

    let lock = builder::build_lock(&manifest, &result);
    let lock_path = root.join("Autoware.lock");
    lock.write(&lock_path).unwrap();

    // Round-trip.
    let loaded = LockFile::read(&lock_path).unwrap();
    assert_eq!(loaded.workspace.autoware, "0.45.1");
    assert_eq!(loaded.components.len(), 6);
    assert!(loaded.packages.is_empty());

    // All components are unpatch.
    for comp in &loaded.components {
        assert!(!comp.patched);
        assert!(comp.patch_image.is_none());
        assert!(comp.extension_image.is_none());
        assert!(comp.digest.starts_with("sha256:"));
    }
}


#[test]
fn lockfile_verify_detects_drift() {
    let manifest = fixture("minimal.toml");
    let (result, _, _, _) = run_pipeline(&manifest);

    let lock = builder::build_lock(&manifest, &result);

    // Tamper with one digest.
    let mut current: Vec<(String, String)> = result
        .step_results
        .iter()
        .map(|s| (s.image.clone(), s.digest.clone()))
        .collect();
    current[0].1 = "sha256:tampered".to_string();

    let mismatches = lock.verify(&current);
    assert_eq!(mismatches.len(), 1);
    assert_eq!(mismatches[0].actual, "sha256:tampered");
}


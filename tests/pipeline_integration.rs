// ===========================================================================
// Scenario 8: Patch + extension on same component (full stack)
// ===========================================================================

#[test]
fn patch_and_extension_same_component() {
    let manifest = parse_inline(
        r#"
        [workspace]
        autoware = "0.45.1"

        [platform]
        arch = "amd64"

        [components]
        localization-mapping = true

        [patch.localization-mapping]
        ndt_scan_matcher = { path = "./patches/ndt" }

        [[package]]
        name    = "my_loc_ext"
        path    = "./src/my_loc_ext"
        extends = "localization-mapping"
        "#,
    );

    let platform = platform::resolve_platform(&manifest.platform).unwrap();
    let plan = resolver::resolve(&manifest, &platform).unwrap();

    let steps = plan.steps_for("localization-mapping");
    assert_eq!(steps.len(), 3, "should have pull + patch + extension");

    // Verify chaining: each step's base_image is the previous step's output.
    if let BuildStep::BuildOverlay { base_image, .. } = steps[1] {
        assert_eq!(base_image, steps[0].output_image());
    }
    if let BuildStep::BuildOverlay { base_image, .. } = steps[2] {
        assert_eq!(base_image, steps[1].output_image());
    }

    // Codegen.
    let dir = tempfile::tempdir().unwrap();
    std::fs::create_dir_all(dir.path().join("patches/ndt")).unwrap();
    std::fs::create_dir_all(dir.path().join("src/my_loc_ext")).unwrap();
    codegen::generate_all(&manifest, &plan, &platform, dir.path()).unwrap();

    // Both Dockerfiles exist.
    assert!(
        dir.path()
            .join(".aw-kit/build/localization-mapping.patch.Dockerfile")
            .exists()
    );
    assert!(
        dir.path()
            .join(".aw-kit/build/localization-mapping.extended.Dockerfile")
            .exists()
    );
}


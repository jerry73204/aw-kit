#[cfg(test)]
mod tests {
    use super::*;

    fn sample_lock() -> LockFile {
        LockFile {
            workspace: LockWorkspace {
                autoware: "0.45.1".to_string(),
                generated: "2026-03-13T10:00:00Z".to_string(),
            },
            components: vec![
                LockedComponent {
                    name: "planning-control".to_string(),
                    image: "ghcr.io/autowarefoundation/openadkit:planning-control".to_string(),
                    digest: "sha256:aaa".to_string(),
                    patched: false,
                    patch_image: None,
                    patch_digest: None,
                    extension_image: None,
                    extension_digest: None,
                },
                LockedComponent {
                    name: "localization-mapping".to_string(),
                    image: "ghcr.io/autowarefoundation/openadkit:localization-mapping".to_string(),
                    digest: "sha256:bbb".to_string(),
                    patched: true,
                    patch_image: Some("localization-mapping-0.45.1-p12345678".to_string()),
                    patch_digest: Some("sha256:ccc".to_string()),
                    extension_image: None,
                    extension_digest: None,
                },
            ],
            packages: vec![],
        }
    }

    #[test]
    fn round_trip_serialization() {
        let lock = sample_lock();
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("Autoware.lock");

        lock.write(&path).unwrap();
        let loaded = LockFile::read(&path).unwrap();
        assert_eq!(lock, loaded);
    }

    #[test]
    fn lock_file_has_header() {
        let lock = sample_lock();
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("Autoware.lock");

        lock.write(&path).unwrap();
        let content = std::fs::read_to_string(&path).unwrap();
        assert!(content.starts_with("# Autoware.lock"));
    }

    #[test]
    fn verify_matching_digests() {
        let lock = sample_lock();
        let current = vec![
            (
                "ghcr.io/autowarefoundation/openadkit:planning-control".to_string(),
                "sha256:aaa".to_string(),
            ),
            (
                "ghcr.io/autowarefoundation/openadkit:localization-mapping".to_string(),
                "sha256:bbb".to_string(),
            ),
            (
                "localization-mapping-0.45.1-p12345678".to_string(),
                "sha256:ccc".to_string(),
            ),
        ];
        let mismatches = lock.verify(&current);
        assert!(mismatches.is_empty());
    }

    #[test]
    fn verify_detects_mismatch() {
        let lock = sample_lock();
        let current = vec![
            (
                "ghcr.io/autowarefoundation/openadkit:planning-control".to_string(),
                "sha256:CHANGED".to_string(),
            ),
            (
                "ghcr.io/autowarefoundation/openadkit:localization-mapping".to_string(),
                "sha256:bbb".to_string(),
            ),
        ];
        let mismatches = lock.verify(&current);
        assert_eq!(mismatches.len(), 1);
        assert_eq!(mismatches[0].expected, "sha256:aaa");
        assert_eq!(mismatches[0].actual, "sha256:CHANGED");
    }

    #[test]
    fn read_nonexistent_file_errors() {
        let result = LockFile::read(Path::new("/tmp/nonexistent-aw-kit-test.lock"));
        assert!(result.is_err());
    }
}
